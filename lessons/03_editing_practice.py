"""Small file for practicing Neovim edits."""


def greet(name: str) -> str:
    return f"Hello, {name}"


def add(left: int, right: int) -> int:
    return left + right


def build_message(customer: str, total: float) -> str:
    return f"{customer}: ${total:.2f}"


def main() -> None:
    name = "Neovim"
    message = greet(name)
    print(message)
    print(build_message("Student", 42.0))


if __name__ == "__main__":
    main()


